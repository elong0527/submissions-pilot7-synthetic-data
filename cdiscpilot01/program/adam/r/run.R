library(yamaa)
stopifnot(as.character(packageVersion("yamaa")) == "0.5.0")
args <- commandArgs(trailingOnly = TRUE)
stopifnot(length(args) == 1L)
root <- normalizePath(args[[1]], mustWork = TRUE)
source(file.path(root, "program/adam/r/assessment.R"))
context <- begin_attempt(root)
tryCatch({
  project <- yamaa_project(file.path(root, "spec/yamaa/project.yaml"))
  checked <- project$check()
  saveRDS(checked$issues, file.path(root, "log/yamaa-preflight-issues.rds"))
  if (nrow(checked$issues)) stop("Resolve preflight issues before running")
  runs <- project$run("adam")
  saveRDS(runs$issues, file.path(root, "log/yamaa-run-issues.rds"))
  saveRDS(runs$report, file.path(root, "log/yamaa-engine-report.rds"))
  missing <- vapply(runs$names, function(x) is.null(runs[[x]]$output), logical(1))
  if (nrow(runs$issues) || any(missing)) stop("Study run incomplete")
  runs$save()
  finish_attempt(context, "success", runs)
}, error = function(error) {
  saveRDS(list(message = conditionMessage(error), issues = error$issues),
          file.path(root, "log/yamaa-failure.rds"))
  finish_attempt(context, "failed")
  stop(error)
})
